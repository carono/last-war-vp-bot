"""The little HTTP server the phone talks to.

Deliberately the standard library and nothing else. The panel installs on other people's
Windows machines out of a `.bat` file, and a remote control that needed a web framework
would be a dependency, a virtualenv and a support question — `http.server` on a thread
is a hundred lines and cannot go out of date.

WHAT IT SERVES. Two things, and it keeps them apart: the PAGE (the files in `static/`,
which are the same for everybody and say nothing about this account) and the API
(`panel/web/api.py`, which is this profile's live state and its buttons). The page is
open, the API needs the token — because the page is useless without one and refusing it
too would only mean a blank screen instead of a login box.

THE TOKEN. One string per WINDOW, generated by the panel and shown in menu → «Веб»
(`panel/runtime/web_control.py`). It travels either as a cookie (set once, by the login
box) or as `?token=…` on the URL, which is what makes the link beside the switch work in
one tap from a phone. Compared with `hmac.compare_digest`, so the comparison does not
leak how much of it was right.

REACHING IT FROM OUTSIDE is the router's business: this listens on every interface, so
a forwarded port is all it takes, and who may connect is the filter on the router. The
traffic is plain HTTP unless a certificate is named in that dialog — a token in a URL is a
token in a browser history and in every hop along the way — so the guessing is bounded
here instead: wrong tokens are counted per address and a sign-in from a new one is said
out loud in the log.
"""
